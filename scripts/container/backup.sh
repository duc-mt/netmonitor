#!/usr/bin/env bash
# Runs INSIDE the "tools" container (see compose.yaml). Do not run it on the host.
# Writes two files to /backups:
#   <name>-db.sql.gz    the LibreNMS database
#   <name>-data.tgz     /data: RRD graphs, config, plugins (logs and cache are skipped)
set -euo pipefail

: "${BACKUP_NAME:?BACKUP_NAME is required}"
DATA_DIR=${DATA_DIR:-/data}
BACKUP_DIR=${BACKUP_DIR:-/backups}
KEEP=${KEEP:-0}

db_file="$BACKUP_DIR/$BACKUP_NAME-db.sql.gz"
data_file="$BACKUP_DIR/$BACKUP_NAME-data.tgz"
mkdir -p "$BACKUP_DIR"

# The password goes through the environment, never onto a command line.
export MYSQL_PWD="${DB_PASSWORD:?DB_PASSWORD is required}"

# Write to .partial files first, so an interrupted run never leaves a truncated backup that looks valid,
# and remove them again if anything fails.
trap 'rm -f "$db_file.partial" "$data_file.partial"' EXIT
echo "Dumping database ${DB_NAME:-librenms} ..."
mariadb-dump -h "${DB_HOST:-db}" -u "${DB_USER:-librenms}" \
  --single-transaction --routines --triggers --default-character-set=utf8mb4 \
  "${DB_NAME:-librenms}" | gzip -6 > "$db_file.partial"   # -6 is gzip's default: -9 is much slower for little gain

echo "Archiving $DATA_DIR ..."
# Logs and cache are rebuilt by LibreNMS, so the archive keeps only the durable data. The directories
# themselves stay in it, and the --exclude options must come before the file list.
tar czf "$data_file.partial" --exclude='./logs/*' --exclude='./cache/*' -C "$DATA_DIR" .

gzip -t "$db_file.partial"
tar tzf "$data_file.partial" > /dev/null
mv "$db_file.partial" "$db_file"
mv "$data_file.partial" "$data_file"

# Files created here belong to root; hand them to the host user (a no-op on Windows and macOS mounts).
chown "${PUID:-0}:${PGID:-0}" "$db_file" "$data_file" 2>/dev/null || true

echo "Backup written:"
# shellcheck disable=SC2012  # file names are generated by these scripts (letters, digits, dashes)
ls -lh "$db_file" "$data_file" | awk '{print "  " $5 "  " $9}'

if [ "$KEEP" -gt 0 ]; then
  # keep the newest $KEEP sets (names sort by timestamp), delete the rest
  # shellcheck disable=SC2012  # file names are generated by these scripts (letters, digits, dashes)
  ls -1 "$BACKUP_DIR"/librenms-*-db.sql.gz 2>/dev/null | sort | head -n -"$KEEP" | while read -r old; do
    echo "Pruning old backup ${old##*/}"
    rm -f "$old" "${old%-db.sql.gz}-data.tgz"
  done
fi
