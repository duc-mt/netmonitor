#!/usr/bin/env bash
# Linux and macOS: restore the database and data volume from ./backups
#
#   scripts/restore.sh latest                      newest backup
#   scripts/restore.sh librenms-20260101-120000    a specific one (or just 20260101-120000)
#   scripts/restore.sh ./backups/20260101-120000   a path or a file name from ./backups also works
#   add --yes to skip the confirmation question
#
# This REPLACES the current database and data. LibreNMS is stopped while it runs.
set -euo pipefail

cd "$(dirname "$0")/.."

YES=0
TARGET=""
for arg in "$@"; do
  case "$arg" in
    --yes|-y) YES=1 ;;
    -h|--help) sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    -*) echo "error: unknown option: $arg" >&2; exit 2 ;;
    *) TARGET=$arg ;;
  esac
done

die() { echo "error: $*" >&2; exit 1; }
[ -n "$TARGET" ] || die "say which backup to restore: 'latest' or a name from ./backups (see --help)"
[ -f .env ] || die "no .env found. Run scripts/setup.sh first."
docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is not available."
docker info >/dev/null 2>&1 || die "The Docker daemon is not running."

# Accept what tab-completion produces: a path and/or the file name with its suffix, for example
# backups/librenms-20260101-120000-db.sql.gz or ./backups/20260101-120000
TARGET=${TARGET##*/}
TARGET=${TARGET%-db.sql.gz}
TARGET=${TARGET%-data.tgz}
[ -n "$TARGET" ] || die "say which backup to restore: 'latest' or a name from ./backups (see --help)"

if [ "$TARGET" = "latest" ]; then
  # shellcheck disable=SC2012  # file names are generated by these scripts (letters, digits, dashes)
  newest=$(ls -1 backups/librenms-*-db.sql.gz 2>/dev/null | sort | tail -n 1 || true)
  [ -n "$newest" ] || die "no backups found in ./backups"
  TARGET=${newest##*/}
  TARGET=${TARGET%-db.sql.gz}
fi
case "$TARGET" in librenms-*) ;; *) TARGET="librenms-$TARGET" ;; esac

if [ ! -f "backups/$TARGET-db.sql.gz" ] || [ ! -f "backups/$TARGET-data.tgz" ]; then
  die "backups/$TARGET-db.sql.gz and backups/$TARGET-data.tgz must both exist"
fi

echo "About to restore '$TARGET'. The current LibreNMS database and data will be REPLACED."
if [ "$YES" -ne 1 ]; then
  printf "Type 'yes' to continue: "
  read -r answer
  [ "$answer" = "yes" ] || die "cancelled"
fi

docker compose stop
docker compose up -d --wait db
docker compose run --rm --no-deps -e "BACKUP_NAME=$TARGET" tools /scripts/restore.sh
docker compose up -d --wait
echo "Restored from $TARGET."
